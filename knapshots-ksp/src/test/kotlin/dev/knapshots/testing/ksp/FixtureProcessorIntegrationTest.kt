package dev.knapshots.testing.ksp

import dev.knapshots.testing.compiler.InlineSnapshotLocation
import dev.knapshots.testing.compiler.SnapshotExpectation
import dev.knapshots.testing.compiler.SnapshotRecording
import dev.knapshots.testing.compiler.snapshot
import java.nio.file.Files
import java.nio.file.Path
import org.junit.jupiter.api.Test
import org.junit.jupiter.api.io.TempDir
import kotlin.test.assertContains
import kotlin.test.assertFailsWith

/** Integration coverage against a real test-only KSP processor. */
class FixtureProcessorIntegrationTest {
  private val version = KotlinVersion.CURRENT.toString()
  private val plugin = Path.of(checkNotNull(System.getProperty("knapshots.fixtureKspJar")))
  private val kspVersion = checkNotNull(System.getProperty("knapshots.fixtureKspVersion"))
  private val host = GradleKspHost(kspVersion, listOf(plugin))
  private val source = """
    package fixture
    @Target(AnnotationTarget.CLASS, AnnotationTarget.FUNCTION)
    annotation class AddGreeting
    @AddGreeting class Example
    fun main() { check(ExampleGreeting.greet() == "Hello, Example!") }
  """.trimIndent()
  private val generated = """
    // FILE: kotlin/fixture/ExampleGreeting.kt
    package fixture

    object ExampleGreeting {
      fun greet(): String = "Hello, Example!"
    }
  """.trimIndent()

  @Test fun `snapshots and runs source generated by a real processor`() {
    assertKsp(source, version, host, generated = SnapshotExpectation(generated), mainClass = "fixture.MainKt")
  }

  @Test fun `processor errors fail compilation with an observable diagnostic`() {
    assertKsp("""
      package fixture
      @Target(AnnotationTarget.CLASS, AnnotationTarget.FUNCTION) annotation class AddGreeting
      @AddGreeting fun invalid() = Unit
    """, version, host, succeeds = false, expectedDiagnostics = listOf(
      KspDiagnosticExpectation(KspDiagnosticSeverity.ERROR, "@AddGreeting requires a class", file = "src/main/kotlin/Main.kt", line = 3),
    ))
  }

  @Test fun `processor warnings are observable`() {
    val warningHost = GradleKspHost(kspVersion, listOf(plugin), processorOptions = mapOf("fixture.warning" to "true"))
    assertKsp(source, version, warningHost, expectedDiagnostics = listOf(
      KspDiagnosticExpectation(KspDiagnosticSeverity.WARNING, "Generating greeting for Example", file = "src/main/kotlin/Main.kt", line = 4),
    ))
  }

  @Test fun `records generated source from the real processor inline`(@TempDir directory: Path) {
    val file = directory.resolve("FixtureTest.kt")
    Files.writeString(file, "fun test() {\n  assertKsp(source = \"example\", generated = snapshot())\n}\n")
    val failure = assertFailsWith<AssertionError> {
      assertKsp(source, version, host, generated = snapshot(), record = SnapshotRecording.MISSING,
        location = InlineSnapshotLocation(file, 2))
    }
    assertContains(failure.message.orEmpty(), "review and rerun")
    val recorded = Files.readString(file)
    assertContains(recorded, "generated = SnapshotExpectation(")
    assertContains(recorded, "object ExampleGreeting")
    assertContains(recorded, "Hello, Example!")
  }

  @Test fun `separate source files can reference generated code`() {
    val definition = "package fixture\nannotation class AddGreeting\n@AddGreeting class Example"
    val use = "package fixture\nfun main() { check(ExampleGreeting.greet() == \"Hello, Example!\") }"
    assertKsp(definition, version, host, generated = SnapshotExpectation(generated),
      additionalSources = listOf(KspSource("Use.kt", use)), mainClass = "fixture.UseKt")
  }
}
