package dev.knapshots.testing.compiler.gradle

import dev.knapshots.testing.compiler.CompilerRequest
import dev.knapshots.testing.compiler.CompilerSource
import dev.knapshots.testing.compiler.CompilerSnapshotKind
import kotlin.test.assertEquals
import kotlin.test.Test
import kotlin.test.assertContains
import kotlin.test.assertFalse
import kotlin.test.assertFailsWith
import kotlin.test.assertTrue

class GradleCompilerHostTest {
  @Test fun `compiles sources and returns class files`() {
    val result = GradleCompilerHost().compile(CompilerRequest(
      listOf(CompilerSource("sample/Example.kt", "package sample\nclass Example")),
      KotlinVersion.CURRENT.toString(), emptySet(),
    ))
    assertTrue(result.succeeded, result.diagnostics.toString())
    assertTrue("sample/Example.class" in result.classFiles)
  }

  @Test fun `reports compilation failure rather than success`() {
    val result = GradleCompilerHost().compile(CompilerRequest(
      listOf(CompilerSource("Example.kt", "val count: Int = \"wrong\"")),
      KotlinVersion.CURRENT.toString(), emptySet(),
    ))
    assertFalse(result.succeeded)
    assertContains(result.diagnostics.single().message, "compileKotlin")
  }

  @Test fun `rejects paths outside the source directory`() {
    assertFailsWith<IllegalArgumentException> {
      GradleCompilerHost().compile(CompilerRequest(
        listOf(CompilerSource("../Escape.kt", "class Escape")),
        KotlinVersion.CURRENT.toString(), emptySet(),
      ))
    }
  }
  @Test fun `runs the fixture plugin through Gradle`() {
    val host = GradleCompilerHost(
      compilerArguments = listOf("-Xplugin=${checkNotNull(System.getProperty("knapshots.fixturePluginJar"))}"),
      captureArguments = { captures -> captures.flatMap { (kind, path) ->
        val option = when (kind) { CompilerSnapshotKind.FIR -> "fir"; CompilerSnapshotKind.IR -> "ir"; else -> error("Unsupported capture") }
        listOf("-P", "plugin:dev.knapshots.fixture:$option=$path")
      } },
    )
    val result = host.compile(CompilerRequest(
      listOf(CompilerSource("Example.kt", "package fixture\nannotation class AddMember\n@AddMember class Example\nfun value() = \"knapshots:input\"\nfun generated() = Example().addedMember()")),
      KotlinVersion.CURRENT.toString(), setOf(CompilerSnapshotKind.FIR, CompilerSnapshotKind.IR),
    ))
    assertTrue(result.succeeded, result.diagnostics.toString())
    assertEquals("FIR classes\nfixture.AddMember\nfixture.Example\n", result.captures[CompilerSnapshotKind.FIR])
    assertEquals("IR replacements: 1\nIR generated members: 1\n", result.captures[CompilerSnapshotKind.IR])
    val module = result.classLoader().loadClass("fixture.ExampleKt")
    assertEquals("knapshots:output", module.getMethod("value").invoke(null))
    assertEquals("generated by fixture", module.getMethod("generated").invoke(null))
  }
}
